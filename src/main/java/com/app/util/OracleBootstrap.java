    private static boolean coreTableExists(Connection c, String tableName) throws Exception {
        try (PreparedStatement ps = c.prepareStatement(
                "SELECT 1 FROM user_tables WHERE table_name = ?")) {
            ps.setString(1, tableName.toUpperCase());
            try (ResultSet rs = ps.executeQuery()) {
                return rs.next();
            }
        }
    }

    private static void mergeSousDirection(Connection c, String name) throws Exception {
        String sql = """
            MERGE INTO sous_directions t
            USING (SELECT ? AS name FROM dual) s
            ON (t.name = s.name)
            WHEN NOT MATCHED THEN INSERT (name) VALUES (s.name)
            """;
        try (PreparedStatement ps = c.prepareStatement(sql)) {
            ps.setString(1, name);
            ps.executeUpdate();
        }
    }

    private static void seedCoreData(Connection c) throws Exception {
        for (String n : new String[] { "AUTRE" }) {
            mergeSousDirection(c, n);
        }

        int autreId;
        try (PreparedStatement q = c.prepareStatement("SELECT id FROM sous_directions WHERE name = 'AUTRE'")) {
            ResultSet rs = q.executeQuery();
            if (!rs.next()) {
                throw new IllegalStateException("AUTRE sous_direction missing");
            }
            autreId = rs.getInt(1);
        }

        String[] directionNames = {
                "Bureau de Coordination",
                "Direction des Ressources Humaines",
                "Direction de la Réglementation et de la Facilitation",
                "Direction de la Lutte contre la Fraude",
                "Direction du Tarif et des Règles d’Origine",
                "Direction des Affaires Juridiques et Contentieuses",
                "Direction de la Valeur",
                "Direction des Huiles Minérales",
                "Direction des Autres Produits d’Accises",
                "Direction des Recettes du Trésor",
                "Direction des Finances Internes",
                "Direction des Équipements et Logistique",
                "Direction des Statistiques, Documentation et Études Économiques",
                com.app.dao.DirectionDAO.CANONICAL_DIRECTION_SYSTEMES_TI,
                "Direction de l’Audit Interne",
                "Direction des Réformes et de la Modernisation"
        };
        String mergeDir = """
            MERGE INTO directions t
            USING (SELECT ? AS name, ? AS sous_direction_id FROM dual) s
            ON (t.name = s.name)
            WHEN NOT MATCHED THEN INSERT (name, sous_direction_id) VALUES (s.name, s.sous_direction_id)
            """;
        try (PreparedStatement ps = c.prepareStatement(mergeDir)) {
            for (String name : directionNames) {
                ps.setString(1, name);
                ps.setInt(2, autreId);
                ps.executeUpdate();
            }
        }

        String mergeDept = """
            MERGE INTO departments t
            USING (SELECT ? AS name FROM dual) s
            ON (t.name = s.name)
            WHEN NOT MATCHED THEN INSERT (name) VALUES (s.name)
            """;
        String[] deptNames = {
                "Bureau de Coordination",
                "Direction des Ressources Humaines",
                "Direction de Réglementation et Facilitation",
                "Direction de la Lutte contre la Fraude",
                "Direction du Tarif et Règles d’origine",
                "Direction des Affaires Juridiques et Contentieuses",
                "Direction de la Valeur",
                "Direction des Huiles Minérales",
                "Direction des Autres Produits d’Accises",
                "Direction des Recettes du Trésor",
                "Direction des Finances Internes",
                "Direction des Equipements et Logistique",
                "Direction des statistiques, Documentation et Etudes Economiques",
                com.app.dao.DirectionDAO.CANONICAL_DIRECTION_SYSTEMES_TI,
                "Direction de l’Audit Interne",
                "Direction de Réformes et Modernisation"
        };
        try (PreparedStatement ps = c.prepareStatement(mergeDept)) {
            for (String name : deptNames) {
                ps.setString(1, name);
                ps.executeUpdate();
            }
        }

        try (PreparedStatement up = c.prepareStatement(
                "UPDATE departments SET escalation_level1 = NULL WHERE escalation_level1 = 0")) {
            up.executeUpdate();
        }
        try (PreparedStatement up = c.prepareStatement(
                "UPDATE departments SET escalation_level2 = NULL WHERE escalation_level2 = 0")) {
            up.executeUpdate();
        }

        String[][] defaultAdmins = {
                {"admin", "admin123"},
                {"admin2", "admin123"},
                {"admin3", "admin123"}
        };
        for (String[] adminData : defaultAdmins) {
            String username = adminData[0];
            String password = adminData[1];
            try (PreparedStatement check = c.prepareStatement("SELECT id FROM users WHERE username = ?")) {
                check.setString(1, username);
                ResultSet rsAdmin = check.executeQuery();
                if (!rsAdmin.next()) {
                    try (PreparedStatement ps = c.prepareStatement("""
                            INSERT INTO users(username, password_hash, role, active, failed_attempts, must_change_password)
                            VALUES (?, ?, 'ADMIN', 1, 0, 0)
                            """)) {
                        ps.setString(1, username);
                        ps.setString(2, BCrypt.hashpw(password, BCrypt.gensalt()));
                        ps.executeUpdate();
                    }
                    System.out.println("Oracle: created default admin: " + username);
                } else {
                    try (PreparedStatement update = c.prepareStatement("""
                            UPDATE users SET password_hash = ?, active = 1, failed_attempts = 0 WHERE username = ?
                            """)) {
                        update.setString(1, BCrypt.hashpw(password, BCrypt.gensalt()));
                        update.setString(2, username);
                        update.executeUpdate();
                    }
                    System.out.println("Oracle: reset admin password: " + username);
                }
            }
        }
    }
