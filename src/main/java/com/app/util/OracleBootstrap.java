    public static void install(Connection c) throws Exception {
        boolean hasStart = coreTableExists(c, "SOUS_DIRECTIONS");
        boolean hasEnd = coreTableExists(c, "MONTHLY_REPORTS");
        if (!hasStart) {
            try (InputStream in = OracleBootstrap.class.getResourceAsStream("/db/oracle/schema.sql")) {
                if (in == null) {
                    throw new IllegalStateException("Missing classpath resource /db/oracle/schema.sql");
                }
                ScriptRunner runner = new ScriptRunner(c);
                runner.setSendFullScript(false);
                runner.setStopOnError(true);
                runner.setLogWriter(null);
                runner.setErrorLogWriter(null);
                runner.runScript(new InputStreamReader(in, StandardCharsets.UTF_8));
            }
        } else if (hasEnd) {
            System.out.println("Oracle schema already exists, skipping schema.sql bootstrap.");
        } else {
            throw new IllegalStateException(
                    "Detected partial Oracle schema bootstrap. Drop/recreate schema user (or DROP USER ... CASCADE) and rerun.");
        }
        seedCoreData(c);
        DB.seedDirectionSousDirectionMappingsOracle(c);
        DB.purgeLegacyAcronymSousDirections(c);
        ensureFieldMissionsTables(c);
        ensureFieldMissionDescriptionColumn(c);
        ensureFieldMissionOrderColumns(c);
        ensureFieldMissionOrderAttachmentsTable(c);
        ensureFieldMissionDetailAttachmentsTable(c);
        ensureFieldMissionReportAuthorColumn(c);
        ensureUserAbsencesTable(c);
        ensureUserAbsencesMissionIdColumn(c);
        ensureCourierTables(c);
        ensureCourierPacketExtraColumns(c);
        ensureCourierPacketExtraDirectionsTable(c);
        ensureMyShiftTables(c);
        ensureMyShiftPlannedTable(c);
        ensureUserOtpColumns(c);
        ensureUserAttendanceSignatureColumn(c);
    }

    private static void ensureUserOtpColumns(Connection c) throws Exception {
        String[] alters = {
                "ALTER TABLE users ADD (password_otp_hash VARCHAR2(255))",
                "ALTER TABLE users ADD (password_otp_expires_at VARCHAR2(32))"
        };
        for (String ddl : alters) {
            try (java.sql.Statement st = c.createStatement()) {
                st.execute(ddl);
            } catch (Exception e) {
                if (e.getMessage() == null
                        || (!e.getMessage().contains("ORA-01430") && !e.getMessage().contains("already exists"))) {
                    System.out.println("Oracle ensureUserOtpColumns: " + e.getMessage());
                }
            }
        }
    }

